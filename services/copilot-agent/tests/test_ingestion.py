"""Hermetic tests for ``app.ingestion`` (P3.1 document ingestion, first
slice: ``doc_type="lab_pdf"``).

Everything here is hermetic: the VLM is a scripted double
(``_FakeVlmOllama``), never a real Ollama call -- mirrors
``tests/test_extraction.py``'s ``_FakeExtractOllama`` pattern. PDF
rendering itself IS real (``pypdfium2`` over the committed fixture,
``tests/fixtures/lab_report_synthetic.pdf``, generated by
``scripts/generate_lab_pdf_fixture.py``) -- it is fast, deterministic, and
needs no model or network.

Pins two contracts:
  1. ``attach_and_extract`` returns schema-valid ``LabResultFact`` objects,
     each carrying a ``Citation`` back to its source page.
  2. The no-fabrication rule: a field the (scripted, standing in for the
     real) VLM could not read comes back ``None``, never a guessed value --
     exercised via the fixture's deliberately redacted field (Creatinine's
     collection date on page 2).
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

import pytest

from app.ingestion import (
    ExtractedLabRow,
    IngestionResult,
    LabPageExtraction,
    LocalIngestionStore,
    attach_and_extract,
    render_pdf_pages_to_png,
)
from app.ollama_client import OllamaError
from app.schemas.ingestion import LabResultFact

_FIXTURE_PATH = Path(__file__).parent / "fixtures" / "lab_report_synthetic.pdf"

# Mirrors scripts/generate_lab_pdf_fixture.py's page content exactly -- the
# scripted double stands in for what a real VLM reading these page images
# would report, including the one deliberately unreadable field (page 2's
# Creatinine collection_date, covered by an opaque box in the fixture).
_PAGE_1_ROWS = [
    ExtractedLabRow(test="Hemoglobin A1c", value="5.4", unit="%", reference_range="4.0-5.6", collection_date="2026-06-01", abnormal_flag="N"),
    ExtractedLabRow(test="Fasting Glucose", value="142", unit="mg/dL", reference_range="70-99", collection_date="2026-06-01", abnormal_flag="H"),
    ExtractedLabRow(test="Total Cholesterol", value="188", unit="mg/dL", reference_range="<200", collection_date="2026-06-01", abnormal_flag="N"),
    ExtractedLabRow(test="LDL Cholesterol", value="112", unit="mg/dL", reference_range="<100", collection_date="2026-06-01", abnormal_flag="H"),
]
_PAGE_2_ROWS = [
    ExtractedLabRow(test="HDL Cholesterol", value="58", unit="mg/dL", reference_range="40-60", collection_date="2026-06-01", abnormal_flag="N"),
    ExtractedLabRow(test="Triglycerides", value="97", unit="mg/dL", reference_range="<150", collection_date="2026-06-01", abnormal_flag="N"),
    ExtractedLabRow(test="TSH", value="2.1", unit="mIU/L", reference_range="0.4-4.0", collection_date="2026-06-01", abnormal_flag="N"),
    # The deliberately unreadable field: collection_date is None, never guessed.
    ExtractedLabRow(test="Creatinine", value="0.9", unit="mg/dL", reference_range="0.6-1.3", collection_date=None, abnormal_flag="N"),
]


class _FakeVlmOllama:
    """Scripted VLM extraction double: returns one canned ``LabPageExtraction``
    per call, in order (or raises), and records what it was called with."""

    def __init__(self, results: list[LabPageExtraction] | None = None, *, error: bool = False) -> None:
        self._results = results or []
        self._error = error
        self.extract_calls: list[tuple[list[dict[str, Any]], type, list[str] | None]] = []

    def extract(
        self, prompt_or_messages: Any, schema: type, *, options: Any = None, images: list[str] | None = None
    ) -> Any:
        self.extract_calls.append((prompt_or_messages, schema, images))
        if self._error:
            raise OllamaError("scripted VLM extraction failure")
        return self._results[len(self.extract_calls) - 1]


@pytest.fixture
def fake_vlm() -> _FakeVlmOllama:
    return _FakeVlmOllama([LabPageExtraction(rows=_PAGE_1_ROWS), LabPageExtraction(rows=_PAGE_2_ROWS)])


@pytest.fixture
def store(tmp_path: Path) -> LocalIngestionStore:
    return LocalIngestionStore(base_dir=tmp_path / "ingestion")


