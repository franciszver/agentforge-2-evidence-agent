def test_render_pdf_pages_to_png_returns_one_image_per_page():
    pages = render_pdf_pages_to_png(_FIXTURE_PATH)

    assert len(pages) == 2
    for page_png in pages:
        assert page_png.startswith(b"\x89PNG\r\n\x1a\n")  # PNG magic bytes


# ---------------------------------------------------------------------------
# 2. attach_and_extract: schema-valid facts + citations
# ---------------------------------------------------------------------------


def test_attach_and_extract_returns_schema_valid_facts_with_citations(fake_vlm, store):
    result = attach_and_extract(
        1, _FIXTURE_PATH, "lab_pdf", ollama_client=fake_vlm, document_store=store, fact_store=store
    )

    assert isinstance(result, IngestionResult)
    assert len(result.facts) == 8  # 4 rows/page x 2 pages
    for fact in result.facts:
        assert isinstance(fact, LabResultFact)
        assert fact.citation.source_type == "lab_pdf"
        assert fact.citation.source_id == result.source_id


def test_attach_and_extract_citations_carry_the_correct_page_number(fake_vlm, store):
    result = attach_and_extract(
        1, _FIXTURE_PATH, "lab_pdf", ollama_client=fake_vlm, document_store=store, fact_store=store
    )

    page_1_facts = [f for f in result.facts if f.test == "Hemoglobin A1c"]
    page_2_facts = [f for f in result.facts if f.test == "HDL Cholesterol"]
    assert page_1_facts[0].citation.page_or_section == "page 1"
    assert page_2_facts[0].citation.page_or_section == "page 2"


def test_attach_and_extract_calls_vlm_once_per_page_with_that_pages_image(fake_vlm, store):
    attach_and_extract(1, _FIXTURE_PATH, "lab_pdf", ollama_client=fake_vlm, document_store=store, fact_store=store)

    assert len(fake_vlm.extract_calls) == 2
    for _messages, schema, images in fake_vlm.extract_calls:
        assert schema is LabPageExtraction
        assert images is not None
        assert len(images) == 1  # one image (this page) per call


def test_attach_and_extract_rejects_unsupported_doc_type(fake_vlm, store):
    with pytest.raises(ValueError, match="lab_pdf"):
        attach_and_extract(
            1, _FIXTURE_PATH, "intake_form", ollama_client=fake_vlm, document_store=store, fact_store=store  # type: ignore[arg-type]
        )


# ---------------------------------------------------------------------------
# 3. No-fabrication: the deliberately unreadable field never gets a guess
# ---------------------------------------------------------------------------


def test_unreadable_field_yields_none_not_a_guessed_value(fake_vlm, store):
    result = attach_and_extract(
        1, _FIXTURE_PATH, "lab_pdf", ollama_client=fake_vlm, document_store=store, fact_store=store
    )

    creatinine = next(f for f in result.facts if f.test == "Creatinine")
    assert creatinine.collection_date is None
    # Every other field on the same row was legible and is NOT None -- proves
    # the None is specific to the unreadable field, not a whole-row failure.
    assert creatinine.value == "0.9"
    assert creatinine.unit == "mg/dL"


def test_unreadable_field_citation_quote_reflects_not_found(fake_vlm, store):
    result = attach_and_extract(
        1, _FIXTURE_PATH, "lab_pdf", ollama_client=fake_vlm, document_store=store, fact_store=store
    )

    creatinine = next(f for f in result.facts if f.test == "Creatinine")
    # The citation's quote is for the row's headline value (legible: "0.9"),
    # not the missing collection_date -- it must never claim a date was read.
    assert "0.9" in creatinine.citation.quote_or_value
    assert "2026" not in creatinine.citation.quote_or_value


def test_all_none_row_citation_quote_says_not_found():
    from app.ingestion import _quote_for_row

    row = ExtractedLabRow(test="Illegible Test", value=None, unit=None, reference_range=None, collection_date=None, abnormal_flag=None)
    assert _quote_for_row(row) == "Illegible Test: (not found)"


def test_extraction_failure_yields_no_facts_for_that_page_not_a_guess(store):
    failing_vlm = _FakeVlmOllama(error=True)

    result = attach_and_extract(
        1, _FIXTURE_PATH, "lab_pdf", ollama_client=failing_vlm, document_store=store, fact_store=store
    )

    # Fails soft, but to EMPTY -- never fabricates rows for a page the VLM
    # couldn't process at all.
    assert result.facts == []


