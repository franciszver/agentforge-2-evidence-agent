def test_local_store_persists_the_source_document_bytes(tmp_path: Path):
    store = LocalIngestionStore(base_dir=tmp_path / "ingestion")

    source_id = store.save_source_document(1, "lab_pdf", _FIXTURE_PATH)

    saved = tmp_path / "ingestion" / "documents" / f"{source_id}.pdf"
    assert saved.read_bytes() == _FIXTURE_PATH.read_bytes()


def test_local_store_persists_facts_as_json(tmp_path: Path, fake_vlm):
    store = LocalIngestionStore(base_dir=tmp_path / "ingestion")

    result = attach_and_extract(
        42, _FIXTURE_PATH, "lab_pdf", ollama_client=fake_vlm, document_store=store, fact_store=store
    )

    saved = tmp_path / "ingestion" / "facts" / f"{result.source_id}.json"
    payload = json.loads(saved.read_text())
    assert payload["patient_id"] == 42
    assert payload["source_id"] == result.source_id
    assert len(payload["facts"]) == 8
    assert payload["facts"][0]["citation"]["source_type"] == "lab_pdf"


def test_local_store_generates_distinct_source_ids(tmp_path: Path):
    store = LocalIngestionStore(base_dir=tmp_path / "ingestion")

    first = store.save_source_document(1, "lab_pdf", _FIXTURE_PATH)
    second = store.save_source_document(1, "lab_pdf", _FIXTURE_PATH)

    assert first != second
